def прогнать_сценарий(модель: str, отчёт: list[Итог]) -> str:
    """Части 3-4: продолжение отложенной задачи в новых процессах."""
    задачи = запустить(Шаг("7.2б", "Найти задачу сценария", ["--задачи"]), модель)
    совпадение = re.search(r"(напиши-фичу-[\w-]+)", задачи.вывод)
    if not совпадение:
        return ""
    task_id = совпадение.group(1)

    заходов = 0
    while заходов < 6:
        заходов += 1
        данные = состояние_задачи(task_id)
        if not данные["пауза"]:
            break
        ждёт_ответа = данные["ожидание"] == "ответ-пользователя"
        ключи = ["--по-шагам", "--задача", task_id]
        ключи += (["--ответ", "Колодцы лежат в gisdata отдельным слоем, SRID 3857."]
                  if ждёт_ответа else ["--продолжить"])
        шаг = Шаг(f"7.{заходов + 2}",
                  "Продолжение в новом процессе"
                  + (" (с ответом на вопрос шага)" if ждёт_ответа else ""),
                  ключи,
                  [("прогон пошёл дальше", по_выражению(r"\d/5|Сценарий отработал|решение")),
                   ("пройденное не переигрывается",
                    lambda текст, н=данные["текущий_шаг"]: f"{н}/5" in текст
                    or "отработал" in текст.lower())])
        итог = запустить(шаг, модель)
        отчёт.append(итог)
        print(f"  {итог.шаг.номер} {итог.шаг.название}: "
              + ("ок" if итог.удача else "РАСХОЖДЕНИЕ"))
        if not os.path.exists(os.path.join(ПАМЯТЬ, "working", f"{task_id}.json")):
            break                                   # задача свёрнута в решение
    return task_id


